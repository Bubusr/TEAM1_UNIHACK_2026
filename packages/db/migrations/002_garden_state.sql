ALTER TABLE pets
  ADD COLUMN IF NOT EXISTS name TEXT NOT NULL DEFAULT 'Mochi',
  ADD COLUMN IF NOT EXISTS exp INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS affection INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS shield_expires_at TIMESTAMPTZ;

CREATE TABLE IF NOT EXISTS pet_interactions (
  id UUID PRIMARY KEY,
  pet_id UUID NOT NULL REFERENCES pets(id),
  user_id UUID NOT NULL REFERENCES users(id),
  action TEXT NOT NULL CHECK (action IN ('feed', 'pet', 'play')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
